import { describe, expect, it } from 'vitest';
import {
  addBusinessDays,
  findNextBusinessDay,
  subtractBusinessDays,
} from '../../src/domain/BusinessDayCalculator';

/**
 * 営業日算術の検証。
 *
 * 前提（全テスト共通）:
 * - businessDates は「営業日リスト」を表す YYYY-MM-DD 文字列の配列で、昇順ソート済みである。
 * - 下記の営業日リストは、1/1〜1/5 を休日とみなし 1/6 から営業日が始まる想定を表す
 *   （実運用では国内ファンドの基準価額の存在日から構築される）。
 */
const 営業日リスト = ['2025-01-06', '2025-01-07', '2025-01-08', '2025-01-09', '2025-01-10'];

describe('findNextBusinessDay', () => {
  it('全営業日より前の日付を与えると最初の営業日を返す', () => {
    // 前提: 1/1 は営業日リストのどの日付よりも前である
    // 検証: 最初の営業日 1/6 が返る
    expect(findNextBusinessDay('2025-01-01', 営業日リスト)).toBe('2025-01-06');
  });

  it('営業日そのものを与えると「翌」営業日を返す（厳密に後の日付）', () => {
    // 前提: 1/7 は営業日リストに存在する
    // 事前条件: 判定は businessDate > date の厳密比較であり、同日は返さない
    // 検証: 1/7 自身ではなく翌営業日 1/8 が返る
    expect(findNextBusinessDay('2025-01-07', 営業日リスト)).toBe('2025-01-08');
  });

  it('非営業日を与えるとその直後の営業日を返す', () => {
    // 前提: 1/5 は営業日リストに存在しない（休日）
    // 検証: 直後の営業日 1/6 が返る
    expect(findNextBusinessDay('2025-01-05', 営業日リスト)).toBe('2025-01-06');
  });

  it('最終営業日以降を与えると null を返す', () => {
    // 前提: 1/10 は営業日リストの最終日である
    // 検証: それより後の営業日は存在しないため null が返る
    expect(findNextBusinessDay('2025-01-10', 営業日リスト)).toBeNull();
  });
});

describe('subtractBusinessDays', () => {
  it('businessDays=0 かつ対象日が営業日なら、その日付をそのまま返す', () => {
    // 前提: 1/8 は営業日リストに存在する
    // 検証: 0営業日前は対象日自身であるため 1/8 が返る
    expect(subtractBusinessDays('2025-01-08', 0, 営業日リスト)).toBe('2025-01-08');
  });

  it('businessDays=0 かつ対象日が非営業日なら null を返す', () => {
    // 前提: 1/5 は営業日リストに存在しない
    // 検証: 0営業日前でも対象日が営業日でなければ null が返る
    expect(subtractBusinessDays('2025-01-05', 0, 営業日リスト)).toBeNull();
  });

  it('N営業日前を、対象日より厳密に前の営業日から数えて返す', () => {
    // 前提: 1/10 を基準に2営業日前を求める
    // 事前条件: 1/10 自身はカウントせず、1/9（1日目）→ 1/8（2日目）と数える
    // 検証: 1/8 が返る
    expect(subtractBusinessDays('2025-01-10', 2, 営業日リスト)).toBe('2025-01-08');
  });

  it('非営業日を基準にしても、それより前の営業日を数える', () => {
    // 前提: 1/11（非営業日）を基準に1営業日前を求める
    // 検証: 1/11 より前の最初の営業日 1/10 が返る
    expect(subtractBusinessDays('2025-01-11', 1, 営業日リスト)).toBe('2025-01-10');
  });

  it('営業日が不足してN番目に到達できない場合は null を返す', () => {
    // 前提: 1/7 より前の営業日は 1/6 の1日しかない
    // 検証: 2営業日前は存在しないため null が返る
    expect(subtractBusinessDays('2025-01-07', 2, 営業日リスト)).toBeNull();
  });
});

describe('addBusinessDays', () => {
  it('businessDays=0 かつ対象日が営業日なら、その日付をそのまま返す', () => {
    // 前提: 1/8 は営業日リストに存在する
    // 検証: 0営業日後は対象日自身であるため 1/8 が返る
    expect(addBusinessDays('2025-01-08', 0, 営業日リスト)).toBe('2025-01-08');
  });

  it('businessDays=0 かつ対象日が非営業日なら null を返す', () => {
    // 前提: 1/5 は営業日リストに存在しない
    // 検証: 0営業日後でも対象日が営業日でなければ null が返る
    expect(addBusinessDays('2025-01-05', 0, 営業日リスト)).toBeNull();
  });

  it('N営業日後を、対象日より厳密に後の営業日から数えて返す', () => {
    // 前提: 1/6 を基準に2営業日後を求める
    // 事前条件: 1/6 自身はカウントせず、1/7（1日目）→ 1/8（2日目）と数える
    // 検証: 1/8 が返る
    expect(addBusinessDays('2025-01-06', 2, 営業日リスト)).toBe('2025-01-08');
  });

  it('非営業日を基準にしても、それより後の営業日を数える', () => {
    // 前提: 1/5（非営業日）を基準に1営業日後を求める
    // 検証: 1/5 より後の最初の営業日 1/6 が返る
    expect(addBusinessDays('2025-01-05', 1, 営業日リスト)).toBe('2025-01-06');
  });

  it('営業日が不足してN番目に到達できない場合は null を返す', () => {
    // 前提: 1/9 より後の営業日は 1/10 の1日しかない
    // 検証: 2営業日後は存在しないため null が返る
    expect(addBusinessDays('2025-01-09', 2, 営業日リスト)).toBeNull();
  });
});
